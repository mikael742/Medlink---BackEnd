    CONSTRAINT FK_OFERTA_INTERESSE FOREIGN KEY (ID_INTERESSE) REFERENCES MDL_INTERESSE (ID),
    CONSTRAINT FK_OFERTA_PACIENTE FOREIGN KEY (ID_PACIENTE) REFERENCES MDL_PACIENTE (ID),
