    TIPO_ATENDIMENTO   VARCHAR2(20) DEFAULT 'QUALQUER' NOT NULL,
    DATA_ENTRADA       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATIVO              CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT FK_INTERESSE_PACIENTE FOREIGN KEY (ID_PACIENTE) REFERENCES MDL_PACIENTE (ID),
    CONSTRAINT FK_INTERESSE_ESPECIALIDADE FOREIGN KEY (ID_ESPECIALIDADE) REFERENCES MDL_ESPECIALIDADE (ID),
    CONSTRAINT FK_INTERESSE_PROFISSIONAL FOREIGN KEY (ID_PROFISSIONAL) REFERENCES MDL_PROFISSIONAL (ID),
    CONSTRAINT FK_INTERESSE_CONSULTA FOREIGN KEY (ID_CONSULTA_ATUAL) REFERENCES MDL_CONSULTA (ID),
    CONSTRAINT CK_INTERESSE_ATIVO CHECK (ATIVO IN ('S', 'N')),
    CONSTRAINT CK_INTERESSE_TIPO CHECK (TIPO_ATENDIMENTO IN ('PRESENCIAL', 'TELECONSULTA', 'QUALQUER'))
);

