CREATE TABLE MDL_ESPECIALIDADE (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME        VARCHAR2(80)  NOT NULL,
    DESCRICAO   VARCHAR2(255),
    CONSTRAINT UK_ESPECIALIDADE_NOME UNIQUE (NOME)
);

CREATE TABLE MDL_CLINICA (
    ID                          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME                        VARCHAR2(120) NOT NULL,
    CNPJ                        VARCHAR2(14)  NOT NULL,
    TELEFONE                    VARCHAR2(20),
    EMAIL                       VARCHAR2(120),
    ENDERECO                    VARCHAR2(200),
    CEP                         VARCHAR2(9),
    LATITUDE                    NUMBER(9,6),
    LONGITUDE                   NUMBER(9,6),
    CONVENIOS_ACEITOS           VARCHAR2(500),
    HORAS_LIMITE_FILA           NUMBER(4)   DEFAULT 24  NOT NULL,
    HORAS_LIMITE_URGENCIA       NUMBER(4)   DEFAULT 6   NOT NULL,
    RAIO_INICIAL_KM             NUMBER(5,1) DEFAULT 5   NOT NULL,
    RAIO_MAXIMO_KM              NUMBER(5,1) DEFAULT 30  NOT NULL,
    PRAZO_RESPOSTA_MIN          NUMBER(5)   DEFAULT 120 NOT NULL,
    PRAZO_RESPOSTA_URGENTE_MIN  NUMBER(5)   DEFAULT 15  NOT NULL,
    CONSTRAINT UK_CLINICA_CNPJ UNIQUE (CNPJ),
    CONSTRAINT CK_CLINICA_HORAS CHECK (HORAS_LIMITE_FILA > HORAS_LIMITE_URGENCIA)
);

CREATE TABLE MDL_PROFISSIONAL (
    ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME              VARCHAR2(120) NOT NULL,
    EMAIL             VARCHAR2(120),
    TELEFONE          VARCHAR2(20),
    CRM               VARCHAR2(20)  NOT NULL,
    ID_ESPECIALIDADE  NUMBER NOT NULL,
    ID_CLINICA        NUMBER NOT NULL,
    CONSTRAINT UK_PROFISSIONAL_CRM UNIQUE (CRM),
    CONSTRAINT FK_PROF_ESPECIALIDADE FOREIGN KEY (ID_ESPECIALIDADE) REFERENCES MDL_ESPECIALIDADE (ID),
    CONSTRAINT FK_PROF_CLINICA FOREIGN KEY (ID_CLINICA) REFERENCES MDL_CLINICA (ID)
);

CREATE TABLE MDL_PACIENTE (
    ID                     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME                   VARCHAR2(120) NOT NULL,
    EMAIL                  VARCHAR2(120),
    TELEFONE               VARCHAR2(20),
    CPF                    VARCHAR2(11)  NOT NULL,
    DATA_NASCIMENTO        DATE,
    CONVENIO               VARCHAR2(40),
    CEP                    VARCHAR2(9),
    LATITUDE               NUMBER(9,6),
    LONGITUDE              NUMBER(9,6),
    CONSENTE_LOCALIZACAO   CHAR(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT UK_PACIENTE_CPF UNIQUE (CPF),
    CONSTRAINT CK_PACIENTE_CONSENTE CHECK (CONSENTE_LOCALIZACAO IN ('S', 'N'))
);

CREATE TABLE MDL_CONSULTA (
    ID                   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PACIENTE          NUMBER NOT NULL,
    ID_PROFISSIONAL      NUMBER NOT NULL,
    DATA_HORA            TIMESTAMP NOT NULL,
    TIPO_ATENDIMENTO     VARCHAR2(20) DEFAULT 'PRESENCIAL' NOT NULL,
    STATUS               VARCHAR2(20) DEFAULT 'AGENDADA'   NOT NULL,
    ORIGEM               VARCHAR2(20) DEFAULT 'NORMAL'     NOT NULL,
    ID_CONSULTA_ORIGEM   NUMBER,
    MOTIVO_CANCELAMENTO  VARCHAR2(255),
    DATA_CANCELAMENTO    TIMESTAMP,
    DATA_CRIACAO         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_CONSULTA_PACIENTE FOREIGN KEY (ID_PACIENTE) REFERENCES MDL_PACIENTE (ID),
    CONSTRAINT FK_CONSULTA_PROFISSIONAL FOREIGN KEY (ID_PROFISSIONAL) REFERENCES MDL_PROFISSIONAL (ID),
    CONSTRAINT FK_CONSULTA_ORIGEM FOREIGN KEY (ID_CONSULTA_ORIGEM) REFERENCES MDL_CONSULTA (ID),
    CONSTRAINT CK_CONSULTA_STATUS CHECK (STATUS IN ('AGENDADA', 'CANCELADA', 'REALIZADA')),
    CONSTRAINT CK_CONSULTA_TIPO CHECK (TIPO_ATENDIMENTO IN ('PRESENCIAL', 'TELECONSULTA')),
    CONSTRAINT CK_CONSULTA_ORIGEM CHECK (ORIGEM IN ('NORMAL', 'ENCAIXE'))
);

CREATE TABLE MDL_INTERESSE (
    ID                 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
