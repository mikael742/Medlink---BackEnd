CREATE TABLE MDL_USUARIO (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL         VARCHAR2(120) NOT NULL,
    SENHA_HASH    VARCHAR2(128) NOT NULL,
    SALT          VARCHAR2(64)  NOT NULL,
    PERFIL        VARCHAR2(10)  NOT NULL,
    ID_PACIENTE   NUMBER,
    ID_CLINICA    NUMBER,
    DATA_CRIACAO  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UK_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIO_PERFIL CHECK (PERFIL IN ('PACIENTE', 'CLINICA')),
    -- cada conta é OU de um paciente OU de uma clínica
    CONSTRAINT CK_USUARIO_DONO CHECK (
        (PERFIL = 'PACIENTE' AND ID_PACIENTE IS NOT NULL AND ID_CLINICA IS NULL) OR
        (PERFIL = 'CLINICA'  AND ID_CLINICA  IS NOT NULL AND ID_PACIENTE IS NULL)),
    CONSTRAINT FK_USUARIO_PACIENTE FOREIGN KEY (ID_PACIENTE) REFERENCES MDL_PACIENTE (ID) ON DELETE CASCADE,
    CONSTRAINT FK_USUARIO_CLINICA FOREIGN KEY (ID_CLINICA) REFERENCES MDL_CLINICA (ID) ON DELETE CASCADE
);

